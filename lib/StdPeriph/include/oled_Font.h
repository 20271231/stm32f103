// 辅助：将 ASCII 映射到数组索引
static inline const unsigned char *oled_get_font(char c)
{
    if (c == ' ') return F6x8[0];
    if (c >= '0' && c <= '9') return F6x8[1 + (c - '0')];
    if (c == ':') return F6x8[11];
    if (c >= 'A' && c <= 'Z') return F6x8[12 + (c - 'A')];
    // 小写转换为大写
    if (c >= 'a' && c <= 'z') return F6x8[12 + (c - 'a')];
    return F6x8[0];
}

